#!/usr/bin/env node
/**
 * tzap's benchmark harness (M7): scenarios from docs/parity-and-benchmarks.md §5, tzap against
 * StrykerJS on the same generated fixture, same machine, same Node, same Vitest.
 *
 *   node tools/bench/bench.mjs [--runs 5] [--stryker-runs 3] [--only S1,S3,...] [--no-stryker]
 *                              [--no-reference] [--no-scaling] [--stryker-concurrency N]
 *                              [--work DIR] [--out tools/bench/results/raw-<platform>.json]
 *   node tools/bench/render.mjs  (turns the raw JSON into report.md and the checked-in text)
 *
 * Method (jzap's lessons, docs/parity-and-benchmarks.md §5):
 * - Median of N with min–max, never a best run. tzap 5 runs, Stryker 3 (it is slow).
 * - tzap and Stryker runs are interleaved, so slow drift in background load hits both.
 * - Work parity next to every time: inventory per tool, the mapped intersection, verdict counts.
 * - S3's patch is derived from the inventory; no figure is recorded when it hits no mutant.
 * - Background CPU load is sampled before every scenario and recorded with it.
 *
 * Where it runs: the fixture (fixtures/bench-vitest, generated by generate.mjs) is copied to a
 * work directory OUTSIDE the repository (default: <os tmp>/tzap-bench), because tzap's discovery
 * walks up to the nearest pnpm-workspace.yaml, and installed there with Vitest 4.1.x: Stryker's
 * Vitest runner 10.0.0 does not work with Vitest 5 (stryker-js#6210), and both tools must run on
 * the same Vitest. tzap itself is the workspace build (packages/tzap/dist/bin.js).
 */
