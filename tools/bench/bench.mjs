const PINS = JSON.parse(readFileSync(path.join(HERE, 'config', 'package.pins.json'), 'utf8'));

function setupVariant(variant) {
  const dir = path.join(WORK, variant);
  const pkg = { name: `tzap-bench-${variant}`, private: true, type: 'module', scripts: { test: 'vitest run' }, devDependencies: PINS };
  const pkgText = `${JSON.stringify(pkg, null, 2)}\n`;
  mkdirSync(dir, { recursive: true });
  let install;
  if (!existsSync(path.join(dir, 'node_modules', 'vitest')) || !existsSync(path.join(dir, 'package.json')) || readFileSync(path.join(dir, 'package.json'), 'utf8') !== pkgText) {
    writeFileSync(path.join(dir, 'package.json'), pkgText);
    log(`install ${variant}: npm install ${Object.entries(PINS).map(([k, v]) => `${k}@${v}`).join(' ')}`);
    const t = performance.now();
    const r = spawnSync('npm install --no-audit --no-fund', { cwd: dir, encoding: 'utf8', shell: true, env: CHILD_ENV });
    if (r.status !== 0) throw new Error(`npm install failed in ${dir}:\n${r.stderr}`);
    install = Math.round(performance.now() - t);
  }
  resetSources(variant);
  cpSync(path.join(HERE, 'config', 'vitest.config.ts'), path.join(dir, 'vitest.config.ts'));
  cpSync(path.join(HERE, 'config', 'stryker.config.json'), path.join(dir, 'stryker.config.json'));
  const vitestVersion = JSON.parse(readFileSync(path.join(dir, 'node_modules', 'vitest', 'package.json'), 'utf8')).version;
  const strykerVersion = JSON.parse(readFileSync(path.join(dir, 'node_modules', '@stryker-mutator', 'core', 'package.json'), 'utf8')).version;
  return { dir, installMs: install, vitestVersion, strykerVersion };
}

function resetSources(variant) {
  const dir = path.join(WORK, variant);
  for (const sub of ['src', 'test', 'reports', '.stryker-tmp']) rmSync(path.join(dir, sub), { recursive: true, force: true });
  cpSync(path.join(FIXTURE, variant, 'src'), path.join(dir, 'src'), { recursive: true });
  cpSync(path.join(FIXTURE, variant, 'test'), path.join(dir, 'test'), { recursive: true });
}

