// ---------------------------------------------------------------------------------------------
// A frozen copy of the tzap build. The workspace is shared: other work rebuilds packages/*/dist
// while a bench runs, and the first full run of this harness mixed two builds inside one scenario
// (phase shapes changed between run 3 and run 4 of S1). Every tzap run therefore uses a snapshot
// taken once, verified to be one consistent build, and identified by its hash in the report.

function listFiles(dir, rel = '') {
  const out = [];
  if (!existsSync(path.join(dir, rel))) return out;
  for (const e of readdirSync(path.join(dir, rel), { withFileTypes: true })) {
    const r = path.join(rel, e.name);
    if (e.isDirectory()) out.push(...listFiles(dir, r));
    else if (/\.(js|mjs|cjs|json)$/.test(e.name) && !e.name.endsWith('.map')) out.push(r);
  }
  return out.sort();
}
function buildHash(pkgDirs) {
  const h = createHash('sha256');
  for (const [name, dist] of pkgDirs) for (const f of listFiles(dist)) h.update(`${name}/${f.split(path.sep).join('/')}|`).update(readFileSync(path.join(dist, f)));
  return h.digest('hex').slice(0, 16);
}
async function snapshotTzap() {
  const pkgs = readdirSync(path.join(REPO, 'packages')).filter((d) => existsSync(path.join(REPO, 'packages', d, 'package.json')));
  const meta = pkgs.map((d) => ({ dir: path.join(REPO, 'packages', d), name: JSON.parse(readFileSync(path.join(REPO, 'packages', d, 'package.json'), 'utf8')).name }));
  const snap = path.join(WORK, 'tzap-build');
  const nm = path.join(snap, 'node_modules');
  for (let attempt = 1; attempt <= 20; attempt++) {
    const before = buildHash(meta.map((m) => [m.name, path.join(m.dir, 'dist')]));
    rmSync(snap, { recursive: true, force: true });
    mkdirSync(nm, { recursive: true });
    for (const m of meta) {
      const to = path.join(nm, ...m.name.split('/'));
      mkdirSync(to, { recursive: true });
      cpSync(path.join(m.dir, 'package.json'), path.join(to, 'package.json'));
      if (existsSync(path.join(m.dir, 'dist'))) cpSync(path.join(m.dir, 'dist'), path.join(to, 'dist'), { recursive: true });
    }
    // Third-party dependencies are linked, not copied: they change only with the lockfile.
    for (const m of meta) {
      const own = path.join(m.dir, 'node_modules');
      if (!existsSync(own)) continue;
      const pj = JSON.parse(readFileSync(path.join(m.dir, 'package.json'), 'utf8'));
      const entries = Object.keys({ ...pj.dependencies, ...pj.optionalDependencies, ...pj.peerDependencies });
      for (const dep of entries) {
        if (dep.startsWith('@tzap/') || !existsSync(path.join(own, ...dep.split('/')))) continue;
        const dest = path.join(nm, ...dep.split('/'));
        if (existsSync(dest)) continue;
        mkdirSync(path.dirname(dest), { recursive: true });
        symlinkSync(realpathSync(path.join(own, ...dep.split('/'))), dest, 'junction');
      }
    }
    const after = buildHash(meta.map((m) => [m.name, path.join(m.dir, 'dist')]));
    const copied = buildHash(meta.map((m) => [m.name, path.join(nm, ...m.name.split('/'), 'dist')]));
    if (before === after && after === copied) return { bin: path.join(nm, 'tzap', 'dist', 'bin.js'), hash: copied, attempts: attempt };
    log(`tzap build changed while it was being copied (attempt ${attempt}); retrying in 10 s`);
    await new Promise((r) => setTimeout(r, 10_000));
  }
  throw new Error('the tzap build kept changing for 20 attempts; run the bench when nothing is rebuilding packages/*/dist');
}

// ---------------------------------------------------------------------------------------------
// Machine and load

function cpuTimes() {
  return os.cpus().map((c) => c.times);
}
async function cpuBusy(ms = 2000) {
  const a = cpuTimes();
  await new Promise((r) => setTimeout(r, ms));
  const b = cpuTimes();
  let busy = 0, total = 0;
  for (let i = 0; i < a.length; i++) {
    const d = (k) => b[i][k] - a[i][k];
    const t = d('user') + d('nice') + d('sys') + d('idle') + d('irq');
    total += t;
    busy += t - d('idle');
  }
  return Math.round((1000 * busy) / total) / 10;
}

function machine() {
  const cpus = os.cpus();
  const git = spawnSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: REPO, encoding: 'utf8' }).stdout.trim();
  const dirty = spawnSync('git', ['status', '--porcelain', '--', 'packages'], { cwd: REPO, encoding: 'utf8' }).stdout.trim() !== '';
  return {
    platform: `${os.type()} ${os.release()} (${process.platform})`,
    cpu: cpus[0]?.model.trim(),
    logicalCpus: os.availableParallelism(),
    memoryGB: Math.round(os.totalmem() / 2 ** 30),
    node: process.version,
    tzapCommit: `${git}${dirty ? '+dirty' : ''}`,
    tzapVersion: spawnSync(process.execPath, [TZAP, '--version'], { encoding: 'utf8' }).stdout.trim(),
    date: new Date().toISOString(),
  };
}

