// S3: a synthetic ~10-line patch derived from the inventory

function inventory(dir, extra = []) {
  const r = spawnSync(process.execPath, [TZAP, 'list-mutants', '--format', 'json', '--no-arid', ...extra], { cwd: dir, encoding: 'utf8', env: CHILD_ENV, maxBuffer: 1 << 28 });
  if (r.status !== 0) throw new Error(`list-mutants failed: ${r.stderr}`);
  return JSON.parse(r.stdout);
}

function makePatch(dir, inv) {
  // Deterministic: two files chosen by a fixed stride over the sorted file list, and in each a
  // window of five consecutive mutant-bearing lines — about ten changed lines, like a small PR.
  const byFile = new Map();
  for (const m of inv) {
    const f = m.file.replace(/\\/g, '/');
    if (!byFile.has(f)) byFile.set(f, new Set());
    byFile.get(f).add(m.location.start.line);
  }
  const files = [...byFile.keys()].sort();
  const chosen = [files[Math.floor(files.length * 0.3)], files[Math.floor(files.length * 0.7)]];
  let diff = '';
  const ranges = [];
  let changed = 0;
  for (const f of chosen) {
    const lines = [...byFile.get(f)].sort((a, b) => a - b);
    const start = Math.floor(lines.length / 3);
    const pickLines = lines.slice(start, start + 5);
    const text = readFileSync(path.join(dir, f), 'utf8').split('\n');
    // Group consecutive lines into hunks.
    const hunks = [];
    for (const l of pickLines) {
      const h = hunks.at(-1);
      if (h && l === h[1] + 1) h[1] = l;
      else hunks.push([l, l]);
    }
    diff += `diff --git a/${f} b/${f}\n--- a/${f}\n+++ b/${f}\n`;
    for (const [a, b] of hunks) {
      const n = b - a + 1;
      diff += `@@ -${a},${n} +${a},${n} @@\n`;
      for (let l = a; l <= b; l++) diff += `-${text[l - 1]} // before\n`;
      for (let l = a; l <= b; l++) diff += `+${text[l - 1]}\n`;
      ranges.push(`${f}:${a}-${b}`);
      changed += n;
    }
  }
  return { diff, ranges, changedLines: changed, files: chosen };
}

