// --- S6: re-run after a one-line change, warm cache ----------------------------------------------
if (ONLY.includes('S6')) {
  // The edit changes a string literal inside code no test reaches, so no verdict should change:
  // what is measured is invalidation scope. Chosen from the primed report, deterministically.
  const target = s5prime.tzap.mutants
    .filter((m) => m.status === 'NoCoverage' && m.mutatorName === 'StringLiteral' && !m.static && m.location.start.line === m.location.end.line && m.original.length > 2)
    .sort((a, b) => a.file.localeCompare(b.file) || a.location.start.line - b.location.start.line)[0];
  if (!target) throw new Error('S6: no uncovered string literal to edit in the fixture');
  const file = path.join(D, target.file.replace(/^.*?\bsrc[\\/]/, 'src/'));
  const original = readFileSync(file, 'utf8');
  const lines = original.split('\n');
  const L = target.location.start.line - 1;
  const lit = target.original;
  const edited = lit.slice(0, -1) + ' (edited)' + lit.slice(-1);
  if (!lines[L].includes(lit)) throw new Error(`S6: literal ${lit} not on line ${L + 1} of ${file}`);
  lines[L] = lines[L].replace(lit, edited);
  const patched = lines.join('\n');
  const cacheFile = path.join(cacheDir('s5'), 'tzap-cache.txt');
  const strykerInc = path.join(D, 'reports', 'stryker-incremental.json');
  // Each repetition restores the pre-change cache: otherwise only the first run does the
  // invalidation work and the median measures a no-change run (jzap's first S6 did exactly that).
  const pristineCache = readFileSync(cacheFile, 'utf8');
  const pristineInc = WITH_STRYKER ? readFileSync(strykerInc, 'utf8') : undefined;
  log(`S6: one-line change at ${target.file}:${L + 1} (${lit} -> ${edited})`);
  const load = await cpuBusy();
  let T, S;
  try {
    writeFileSync(file, patched);
    ({ T, S } = await interleaved(
      RUNS,
      WITH_STRYKER ? STRYKER_RUNS : 0,
      () => {
        writeFileSync(cacheFile, pristineCache);
        return tzap(D, ['--cache-dir', cacheDir('s5')], { reportDir: rep('s6') });
      },
      () => {
        writeFileSync(strykerInc, pristineInc);
        return stryker(D, ['--concurrency', String(strykerConcurrency ?? 4), '--incremental']);
      },
      'S6',
    ));
  } finally {
    writeFileSync(file, original);
  }
  const S6 = (results.scenarios.S6 = {
    title: 'Re-run after a one-line change, warm cache',
    load,
    edit: { file: target.file, line: L + 1, from: lit, to: edited },
    series: [series('tzap warm, --cache-dir (pre-change cache restored each run)', 'tzap', T)],
  });
  if (T.some((r) => r.redTests > 0)) S6.warning = 'the edit turned a test red; the scenario no longer isolates invalidation';
  if (S.length) S6.series.push(series(`StrykerJS --incremental (pre-change file restored each run), concurrency ${strykerConcurrency}`, 'stryker', S));
  save();
}

