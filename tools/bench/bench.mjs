/** Spawns a command, timestamping every output line on arrival (for phase attribution). */
function exec(cmd, args, cwd) {
  return new Promise((resolve) => {
    const t0 = performance.now();
    const child = spawn(cmd, args, { cwd, env: CHILD_ENV });
    const lines = [];
    let buf = { out: '', err: '' };
    const take = (k) => (chunk) => {
      buf[k] += chunk.toString();
      let i;
      while ((i = buf[k].indexOf('\n')) >= 0) {
        lines.push({ t: performance.now() - t0, k, s: buf[k].slice(0, i).replace(/\x1b\[[0-9;]*m/g, '') });
        buf[k] = buf[k].slice(i + 1);
      }
    };
    child.stdout.on('data', take('out'));
    child.stderr.on('data', take('err'));
    child.on('close', (code) => resolve({ code, ms: performance.now() - t0, lines }));
  });
}

const count = (ms, f = (m) => m.status) => ms.reduce((c, m) => ((c[f(m)] = (c[f(m)] ?? 0) + 1), c), {});

async function tzap(dir, args, { reportDir }) {
  rmSync(reportDir, { recursive: true, force: true });
  const r = await exec(process.execPath, [TZAP, 'run', '-r', 'json', '-o', reportDir, '--no-arid', '-q', ...args], dir);
  if (r.code !== 0 && r.code !== 1) throw new Error(`tzap exited ${r.code} in ${dir} (${args.join(' ')}):\n${r.lines.slice(-20).map((l) => l.s).join('\n')}`);
  const rep = JSON.parse(readFileSync(path.join(reportDir, 'tzap.json'), 'utf8'));
  const ms = rep.mutants;
  const executed = ms.filter((m) => !m.cached && (m.testsCompleted ?? 0) > 0);
  const testsRun = executed.reduce((a, m) => a + (m.testsCompleted ?? 0), 0);
  return {
    ms: Math.round(r.ms),
    phases: rep.timings,
    inventory: ms.length,
    executed: executed.length,
    cached: ms.filter((m) => m.cached).length,
    static: ms.filter((m) => m.static).length,
    testExecutions: testsRun,
    verdicts: count(ms),
    redTests: rep.redTests?.length ?? 0,
    mutants: ms,
  };
}

function strykerMutants(report) {
  const out = [];
  for (const [file, f] of Object.entries(report.files)) for (const m of f.mutants) out.push({ ...m, file });
  return out;
}

async function stryker(dir, args) {
  rmSync(path.join(dir, '.stryker-tmp'), { recursive: true, force: true });
  rmSync(path.join(dir, 'reports', 'stryker.json'), { force: true });
  const bin = path.join(dir, 'node_modules', '@stryker-mutator', 'core', 'bin', 'stryker.js');
  const r = await exec(process.execPath, [bin, 'run', ...args], dir);
  const reportFile = path.join(dir, 'reports', 'stryker.json');
  if (r.code !== 0 || !existsSync(reportFile)) throw new Error(`stryker exited ${r.code} in ${dir} (${args.join(' ')}):\n${r.lines.slice(-30).map((l) => l.s).join('\n')}`);
  const ms = strykerMutants(JSON.parse(readFileSync(reportFile, 'utf8')));
  const at = (re) => r.lines.find((l) => re.test(l.s))?.t;
  const instrumented = at(/Instrumented \d+ source file/);
  const dryStart = at(/Starting initial test run/);
  const dryEnd = at(/Initial test run succeeded/);
  const reusedLine = r.lines.find((l) => /mutant result\(s\) are reused/.test(l.s))?.s;
  const reused = reusedLine ? Number(/(\d+) of \d+ mutant result/.exec(reusedLine)[1]) : 0;
  const executed = ms.filter((m) => (m.testsCompleted ?? 0) > 0 && m.status !== 'NoCoverage');
  return {
    ms: Math.round(r.ms),
    phases: {
      startup_instrument: instrumented !== undefined ? Math.round(instrumented) : undefined,
      dryRun: dryStart !== undefined && dryEnd !== undefined ? Math.round(dryEnd - dryStart) : undefined,
      mutate: dryEnd !== undefined ? Math.round(r.ms - dryEnd) : undefined,
    },
    inventory: ms.length,
    // Reused results carry their old testsCompleted; count them out of the executed figure.
    executed: Math.max(0, executed.length - reused),
    cached: reused,
    static: ms.filter((m) => m.static).length,
    testExecutions: reused ? undefined : executed.reduce((a, m) => a + (m.testsCompleted ?? 0), 0),
    verdicts: count(ms),
    mutants: ms,
  };
}

// ---------------------------------------------------------------------------------------------
// Work parity: Stryker's incremental key, replacement normalised (both tools print parentheses and
// whitespace differently), per docs/parity-and-benchmarks.md §3.

const norm = (s) => String(s).replace(/[\s()]/g, '').replace(/"/g, "'");
const key = (m) => `${m.file.replace(/\\/g, '/').replace(/^.*?\bsrc\//, 'src/')}:${m.location.start.line}:${m.location.start.column}-${m.location.end.line}:${m.location.end.column} ${m.mutatorName} ${norm(m.replacement)}`;

function parity(a, b) {
  const A = new Map(a.map((m) => [key(m), m]));
  const B = new Map(b.map((m) => [key(m), m]));
  const shared = [...A.keys()].filter((k) => B.has(k));
  const disagree = {};
  for (const k of shared) {
    const x = A.get(k).status, y = B.get(k).status;
    if (x !== y) disagree[`${x}/${y}`] = (disagree[`${x}/${y}`] ?? 0) + 1;
  }
  const only = (X, Y) => [...X.keys()].filter((k) => !Y.has(k));
  const aOnly = only(A, B), bOnly = only(B, A);
  return { shared: shared.length, aOnly: aOnly.length, bOnly: bOnly.length, aOnlySample: aOnly.slice(0, 5), bOnlySample: bOnly.slice(0, 5), disagree };
}

const strip = ({ mutants, ...rest }) => rest;

