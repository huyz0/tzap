function series(label, tool, runs, extra = {}) {
  return { label, tool, runs: runs.map(strip), ...extra };
}

async function timed(label, n, fn) {
  const out = [];
  for (let i = 0; i < n; i++) {
    const r = await fn(i);
    out.push(r);
    log(`  ${label} ${i + 1}/${n}: ${(r.ms / 1000).toFixed(2)}s  inv=${r.inventory} exec=${r.executed}${r.cached ? ` cached=${r.cached}` : ''} ${JSON.stringify(r.verdicts)}`);
  }
  return out;
}

/** Interleaves tzap (n runs) and Stryker (m runs) so background drift hits both alike. */
async function interleaved(nT, nS, runT, runS, label) {
  const T = [], S = [];
  for (let i = 0; i < Math.max(nT, nS); i++) {
    if (i < nT) {
      const r = await runT(i);
      T.push(r);
      log(`  ${label} tzap ${i + 1}/${nT}: ${(r.ms / 1000).toFixed(2)}s inv=${r.inventory} exec=${r.executed}${r.cached ? ` cached=${r.cached}` : ''} ${JSON.stringify(r.verdicts)}`);
    }
    if (i < nS) {
      const r = await runS(i);
      S.push(r);
      log(`  ${label} stryker ${i + 1}/${nS}: ${(r.ms / 1000).toFixed(2)}s inv=${r.inventory} exec=${r.executed}${r.cached ? ` reused=${r.cached}` : ''} ${JSON.stringify(r.verdicts)}`);
    }
  }
  return { T, S };
}

